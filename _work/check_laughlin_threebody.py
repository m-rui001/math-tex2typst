def Uf(c,z,T,p):
    if z>T or p>T: return 0
    s=0
    for h in range(max(0,p+z-T),min(p,z)+1):
        s+= (-1)**(z-h)*math.comb(z,h)*math.comb(T-z,p-h)*c**(p-h)
    return s
