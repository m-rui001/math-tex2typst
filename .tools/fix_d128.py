import io

f = '研究笔记/D128-平面曲线的Nagata猜想：约化、椭圆线与极限的重数不等式反推笔记.md'
t = io.open(f, encoding='utf-8').read()

i0 = t.index('要清的 $5$ 个破折号在')
i1 = t.index('这样收稿后 grep')
assert i0 < i1
new_mid = ('那 $5$ 个破折号在 `第 2、13、14、16、17 节`：第 2 节"闭子集"之后、第 13 节"$=q$ 的几何再现"之前、'
           '第 14 节"单射"之后、第 16 节"正面用途"之后、第 17 节"列满秩失败"之后。那 $3$ 个先否定句式在 '
           '`第 2、8、11 节`，清理批的改法是第 2 节改成直陈"放弃纯计数、改靠闭集"，第 8 节改成'
           '"参数是被逼着让切片长度等于 $q$ 才定下的"，第 11 节把对举改成"改把相关压进数值矩阵"，两处均不再复述原句。')
t = t[:i0] + new_mid + t[i1:]

pairs = [
    ('我不再靠数条件，而是靠', '我放弃纯计数，改靠'),
    ('参数不是随手设，而是逼着切片长度等于 $q$。', '参数是被逼着让切片长度等于 $q$ 才定下的。'),
    ('不直接控制相关，而是把相关压进一个', '不直接控制相关，改把相关压进一个'),
    ('的一个闭子集——这里我卡了一下', '的一个闭子集，这里我卡了一下'),
    ('（04-interpolation.tex:224-227）——这正是', '（04-interpolation.tex:224-227），这正是'),
    ('单射——直接套', '单射，直接套'),
    ('正面用途——计数给', '正面用途，计数给'),
    ('列满秩失败"——机器侧的', '列满秩失败"。机器侧的'),
]
for old, new in pairs:
    c = t.count(old)
    assert c == 1, (old, c)
    assert '而是' not in new and '——' not in new, old
    t = t.replace(old, new)

io.open(f, 'w', encoding='utf-8', newline='\n').write(t)
print('ershi', t.count('而是'), 'emDash', t.count('—'), 'size', len(t.encode()))
